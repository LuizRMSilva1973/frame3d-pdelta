"""Runs the OpenSees cross-checks and the gamma_z comparison and writes VALIDATION.md."""

import platform
from importlib.metadata import version
from pathlib import Path

import numpy as np

from examples.building import build
from frame3d import gamma_z, solve_linear, solve_pdelta
from frame3d.opensees_ref import run_opensees

GROUPS = {"N": [0, 6], "Vy": [1, 7], "Vz": [2, 8], "T": [3, 9], "My": [4, 10], "Mz": [5, 11]}


def compare(model):
    rows = []
    for pdelta in (False, True):
        ours = solve_pdelta(model) if pdelta else solve_linear(model)
        ref = run_opensees(model, pdelta=pdelta)
        scale_q = np.abs(ref.local_forces).max()
        row = {
            "analysis": "P-Delta" if pdelta else "First order",
            "u": np.abs(ours.displacements - ref.displacements).max() / np.abs(ref.displacements).max(),
            "R": np.abs(ours.reactions - ref.reactions).max() / np.abs(ref.reactions).max(),
        }
        for name, idx in GROUPS.items():
            row[name] = np.abs(ours.local_forces[:, idx] - ref.local_forces[:, idx]).max() / scale_q
        row["iterations"] = ours.iterations
        rows.append(row)
    return rows


def main():
    model, ids = build()
    top = ids[1, 1, 6]
    rows = compare(model)
    u1, u2 = solve_linear(model), solve_pdelta(model)
    gz = gamma_z(model, u1, direction=(1, 0, 0))
    amp = u2.displacements[top, 0] / u1.displacements[top, 0]

    out = ["# Validation against OpenSees", ""]
    out.append("Generated by `python -m examples.validation_report`. Relative difference = "
               "max |ours − OpenSees| / max |OpenSees| over all nodes or elements.")
    out.append("")
    out.append(f"Model: `examples/building.py`, {model.n_nodes} nodes, {len(model.elements)} elements "
               "(6 storeys, 3 × 3 column grid, gravity on beams + wind in +X, design values).")
    out.append("")
    out.append("| Analysis | Displacements | Reactions | N | Vy | Vz | T | My | Mz | Iterations |")
    out.append("|---|---|---|---|---|---|---|---|---|---|")
    for r in rows:
        out.append(f"| {r['analysis']} | {r['u']:.1e} | {r['R']:.1e} | " +
                   " | ".join(f"{r[k]:.1e}" for k in GROUPS) + f" | {r['iterations']} |")
    out.append("")
    out.append("## Global stability")
    out.append("")
    out.append("| Quantity | Value |")
    out.append("|---|---|")
    out.append(f"| Top drift X, first order | {u1.displacements[top, 0] * 1e3:.3f} mm |")
    out.append(f"| Top drift X, P-Delta | {u2.displacements[top, 0] * 1e3:.3f} mm |")
    out.append(f"| P-Delta amplification of top drift | {amp:.4f} |")
    out.append(f"| M1,tot,d (first-order overturning moment) | {gz.M1:.1f} kN·m |")
    out.append(f"| ΔMtot,d | {gz.dM:.2f} kN·m |")
    out.append(f"| γz (NBR 6118, 15.5.3) | {gz.gamma_z:.4f} |")
    out.append(f"| γz / amplification − 1 | {gz.gamma_z / amp - 1:+.2%} |")
    out.append("")
    out.append("## Environment")
    out.append("")
    out.append(f"Python {platform.python_version()}, NumPy {version('numpy')}, "
               f"OpenSeesPy {version('openseespy')}.")
    out.append("")
    Path(__file__).resolve().parents[1].joinpath("VALIDATION.md").write_text("\n".join(out), encoding="utf-8")
    print("\n".join(out))


if __name__ == "__main__":
    main()
